
"""
MODULE NAME
-----------
FRONTEND AUTHENTICATION PAGE

PURPOSE
-------
Provide a lightweight browser interface for account
registration, login, authentication status, and logout.

Authentication is performed by the existing FastAPI
frontend endpoints. This module never handles JWTs.

ENVIRONMENT / CONFIGURATION
---------------------------
No additional environment variables.

DEPENDENCIES
------------
Python standard library.

RESPONSIBILITIES / WHAT WE TEST
-------------------------------
- Render accessible authentication forms.
- Submit requests to same-origin FastAPI endpoints.
- Display safe success and error messages.
- Check authentication status after page loading.
- Avoid browser-side credential persistence.

SECURITY NOTES
--------------
- Passwords are not stored in localStorage or sessionStorage.
- Backend access and refresh tokens remain server-side.
- The server supplies a unique CSP nonce per response.
- User-controlled values are never inserted into HTML.
- Gradio event endpoints remain disabled.
"""

from __future__ import annotations

from html import escape


def render_auth_page(*, script_nonce: str) -> str:
    """
    Render the authentication page with a CSP nonce.

    Parameters
    ----------
    script_nonce:
        Cryptographically random nonce generated by the
        HTTP server for this individual response.

    Returns
    -------
    str
        Complete HTML document.
    """

    if not script_nonce:
        raise ValueError("A CSP script nonce is required.")

    nonce = escape(script_nonce, quote=True)

    return """<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport"
      content="width=device-width, initial-scale=1">

<title>Health Advisor | Authentication</title>

<style>
:root {
    font-family: system-ui, sans-serif;
    color-scheme: dark;
}

* {
    box-sizing: border-box;
}

body {
    margin: 0;
    min-height: 100vh;
    background: #12141a;
    color: #f5f5f7;
    display: grid;
    place-items: center;
}

main {
    width: min(440px, calc(100% - 32px));
    background: #20232c;
    border: 1px solid #393d49;
    border-radius: 14px;
    padding: 32px;
}

h1 {
    font-size: 25px;
    margin-top: 0;
}

h2 {
    font-size: 19px;
}

p {
    color: #c4c6cf;
    line-height: 1.6;
}

label {
    display: block;
    margin: 18px 0 7px;
}

input {
    display: block;
    width: 100%;
    padding: 12px;
    border: 1px solid #626675;
    border-radius: 7px;
    background: #14161c;
    color: #ffffff;
    font: inherit;
}

button {
    margin-top: 20px;
    padding: 12px 18px;
    border: none;
    border-radius: 7px;
    background: #8068df;
    color: white;
    font: inherit;
    cursor: pointer;
}

button:disabled {
    opacity: 0.5;
    cursor: wait;
}

.secondary {
    background: transparent;
    color: #c5b7ff;
    padding-left: 0;
}

.hidden {
    display: none;
}

#message {
    min-height: 24px;
    overflow-wrap: anywhere;
}

input:focus-visible,
button:focus-visible {
    outline: 2px solid #c5b7ff;
    outline-offset: 3px;
}
</style>
</head>

<body>
<main>
<h1>Health Risk &amp; Cost Advisor</h1>

<p>
    Secure access to your insurance policy workspace.
</p>

<section id="auth-section">
    <form id="auth-form">
        <h2 id="form-heading">Sign in</h2>

        <label for="email">Email address</label>
        <input
            id="email"
            name="email"
            type="email"
            autocomplete="email"
            maxlength="254"
            required
        >

        <label for="password">Password</label>
        <input
            id="password"
            name="password"
            type="password"
            autocomplete="current-password"
            minlength="1"
            maxlength="1024"
            required
        >

        <button id="submit-button" type="submit">
            Sign in
        </button>
    </form>

    <button
        id="switch-button"
        class="secondary"
        type="button"
    >
        Create an account
    </button>
</section>

<section id="authenticated-section" class="hidden">
    <h2>Signed in</h2>

    <p>
        Your browser session is authenticated.
        The protected policy workspace will be
        connected in a subsequent phase.
    </p>

    <button id="logout-button" type="button">
        Sign out
    </button>
</section>

<p id="message" role="status" aria-live="polite"></p>
</main>

<script nonce="__SCRIPT_NONCE__">
"use strict";

const authForm = document.getElementById("auth-form");
const authSection = document.getElementById("auth-section");
const authenticatedSection = document.getElementById(
    "authenticated-section"
);

const formHeading = document.getElementById("form-heading");
const submitButton = document.getElementById("submit-button");
const switchButton = document.getElementById("switch-button");
const logoutButton = document.getElementById("logout-button");

const emailInput = document.getElementById("email");
const passwordInput = document.getElementById("password");
const message = document.getElementById("message");

let registrationMode = false;

function showMessage(text) {
    message.textContent = text;
}

function setAuthenticated(authenticated) {
    authSection.classList.toggle(
        "hidden",
        authenticated
    );

    authenticatedSection.classList.toggle(
        "hidden",
        !authenticated
    );

    passwordInput.value = "";
}

function setRegistrationMode(enabled) {
    registrationMode = enabled;

    formHeading.textContent = enabled
        ? "Create account"
        : "Sign in";

    submitButton.textContent = enabled
        ? "Register"
        : "Sign in";

    switchButton.textContent = enabled
        ? "Already registered? Sign in"
        : "Create an account";

    passwordInput.autocomplete = enabled
        ? "new-password"
        : "current-password";

    passwordInput.minLength = enabled ? 12 : 1;
    passwordInput.value = "";

    showMessage("");
}

async function sendRequest(path, payload) {
    const response = await fetch(path, {
        method: "POST",
        credentials: "same-origin",
        cache: "no-store",
        headers: {
            "Content-Type": "application/json"
        },
        body: JSON.stringify(payload)
    });

    let result = {};

    try {
        result = await response.json();
    } catch {
        throw new Error(
            "The server returned an unexpected response."
        );
    }

    if (!response.ok) {
        throw new Error(
            typeof result.detail === "string"
                ? result.detail
                : "The request could not be completed."
        );
    }

    return result;
}

async function checkStatus() {
    try {
        const response = await fetch(
            "/frontend-auth/status",
            {
                method: "GET",
                credentials: "same-origin",
                cache: "no-store"
            }
        );

        if (!response.ok) {
            throw new Error("Status request failed.");
        }

        const result = await response.json();

        setAuthenticated(
            result.authenticated === true
        );
    } catch {
        setAuthenticated(false);
        showMessage(
            "Unable to verify your session. "
            + "Please reload the page."
        );
    }
}

authForm.addEventListener("submit", async (event) => {
    event.preventDefault();

    submitButton.disabled = true;
    switchButton.disabled = true;

    showMessage("");

    const email = emailInput.value.trim();
    const password = passwordInput.value;

    try {
        if (registrationMode) {
            await sendRequest(
                "/frontend-auth/register",
                { email, password }
            );

            setRegistrationMode(false);

            showMessage(
                "Account created. Please sign in."
            );
        } else {
            await sendRequest(
                "/frontend-auth/login",
                { email, password }
            );

            // Confirm state from the server rather
            // than trusting a local JavaScript flag.
            await checkStatus();
        }
    } catch (error) {
        showMessage(error.message);
    } finally {
        passwordInput.value = "";
        submitButton.disabled = false;
        switchButton.disabled = false;
    }
});

switchButton.addEventListener("click", () => {
    setRegistrationMode(!registrationMode);
});

logoutButton.addEventListener("click", async () => {
    logoutButton.disabled = true;
    showMessage("");

    try {
        await sendRequest(
            "/frontend-auth/logout",
            {}
        );

        setAuthenticated(false);
        showMessage("Signed out successfully.");
    } catch {
        // Logout failures must not be presented
        // as confirmed backend revocation.
        setAuthenticated(false);

        showMessage(
            "Browser access was cleared, but "
            + "server logout could not be confirmed. "
            + "Please reload the page."
        );
    } finally {
        logoutButton.disabled = false;
    }
});

checkStatus();
</script>
</body>
</html>""".replace("__SCRIPT_NONCE__", nonce)